/// Render the shared `dtos.ts` file for `dtos`.
pub fn render_dtos(dtos: &[DtoInfo]) -> String {
    let mut out = vec![
        GENERATED_BANNER.to_string(),
        "/* eslint-disable */".to_string(),
    ];
    for dto in dtos {
        out.push(String::new());
        out.push(match dto {
            DtoInfo::Struct(s) => render_struct(s),
            DtoInfo::Enum(e) => render_enum(e),
        });
    }
    out.join("\n") + "\n"
}

fn render_struct(s: &StructInfo) -> String {
    let active: Vec<&FieldInfo> = s.fields.iter().filter(|f| !f.skip).collect();
    let mut l = Vec::new();

    l.push(format!("export interface {} {{", s.name));
    for f in &active {
        l.push(format!("  {}: {};", f.ts_name, f.ts_type));
    }
    l.push("}".into());
    l.push(String::new());

    // decode
    l.push(format!(
        "export function decode{}(json: any): {} {{",
        s.name, s.name
    ));
    l.push("  return {".into());
    for f in &active {
        let expr = f.ts.decode(&format!("json[{:?}]", f.json_name));
        l.push(format!("    {}: {expr},", f.ts_name));
    }
    l.push("  };".into());
    l.push("}".into());
    l.push(String::new());

    // encode
    l.push(format!(
        "export function encode{}(value: {}): any {{",
        s.name, s.name
    ));
    l.push("  return {".into());
    for f in &active {
        let expr = f.ts.encode(&format!("value.{}", f.ts_name));
        l.push(format!("    {:?}: {expr},", f.json_name));
    }
    l.push("  };".into());
    l.push("}".into());

    l.join("\n")
}

fn render_enum(e: &EnumInfo) -> String {
    match &e.repr {
        EnumRepr::External => render_enum_external(e),
        EnumRepr::Internal { tag } => render_enum_internal(e, tag),
    }
}

fn render_enum_external(e: &EnumInfo) -> String {
    let mut l = Vec::new();

    // union type
    l.push(format!("export type {} =", e.name));
    let mut arms: Vec<String> = Vec::new();
    for v in &e.variants {
        arms.push(match &v.kind {
            VariantKind::Unit => format!("{:?}", v.json_name),
            VariantKind::Newtype { ts_type, .. } => {
                format!("{{ {:?}: {ts_type} }}", v.json_name)
            }
            VariantKind::Struct { fields } => {
                let inner = fields
                    .iter()
                    .filter(|f| !f.skip)
                    .map(|f| format!("{}: {}", f.ts_name, f.ts_type))
                    .collect::<Vec<_>>()
                    .join("; ");
                format!("{{ {:?}: {{ {inner} }} }}", v.json_name)
            }
        });
    }
    for (i, arm) in arms.iter().enumerate() {
        let term = if i + 1 == arms.len() { ";" } else { "" };
        l.push(format!("  | {arm}{term}"));
    }
    l.push(String::new());

    // decode
    l.push(format!(
        "export function decode{}(json: any): {} {{",
        e.name, e.name
    ));
    let has_unit = e
        .variants
        .iter()
        .any(|v| matches!(v.kind, VariantKind::Unit));
    if has_unit {
        l.push("  if (typeof json === \"string\") {".into());
        l.push("    switch (json) {".into());
        for v in &e.variants {
            if matches!(v.kind, VariantKind::Unit) {
                l.push(format!(
                    "      case {:?}: return {:?};",
                    v.json_name, v.json_name
                ));
            }
        }
        l.push(format!(
            "      default: throw new Error(`Unknown {} variant: ${{json}}`);",
            e.name
        ));
        l.push("    }".into());
        l.push("  }".into());
    }
    l.push("  if (json && typeof json === \"object\") {".into());
    for v in &e.variants {
        match &v.kind {
            VariantKind::Newtype { ts, .. } => {
                let expr = ts.decode(&format!("json[{:?}]", v.json_name));
                l.push(format!(
                    "    if ({:?} in json) return {{ {:?}: {expr} }};",
                    v.json_name, v.json_name
                ));
            }
            VariantKind::Struct { fields } => {
                let inner = fields
                    .iter()
                    .filter(|f| !f.skip)
                    .map(|f| {
                        let e =
                            f.ts.decode(&format!("json[{:?}][{:?}]", v.json_name, f.json_name));
                        format!("{}: {e}", f.ts_name)
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                l.push(format!(
                    "    if ({:?} in json) return {{ {:?}: {{ {inner} }} }};",
                    v.json_name, v.json_name
                ));
            }
            VariantKind::Unit => {}
        }
    }
    l.push("  }".into());
    l.push(format!(
        "  throw new Error(`Unknown {}: ${{JSON.stringify(json)}}`);",
        e.name
    ));
    l.push("}".into());
    l.push(String::new());

    // encode
    l.push(format!(
        "export function encode{}(value: {}): any {{",
        e.name, e.name
    ));
    for v in &e.variants {
        match &v.kind {
            VariantKind::Unit => {
                l.push(format!(
                    "  if (value === {:?}) return {:?};",
                    v.json_name, v.json_name
                ));
            }
            VariantKind::Newtype { ts, .. } => {
                let expr = ts.encode(&format!("(value as any)[{:?}]", v.json_name));
                l.push(format!(
                    "  if (typeof value === \"object\" && {:?} in value) return {{ {:?}: {expr} }};",
                    v.json_name, v.json_name
                ));
            }
            VariantKind::Struct { fields } => {
                let inner = fields
                    .iter()
                    .filter(|f| !f.skip)
                    .map(|f| {
                        let e = f
                            .ts
                            .encode(&format!("(value as any)[{:?}].{}", v.json_name, f.ts_name));
                        format!("{:?}: {e}", f.json_name)
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                l.push(format!(
                    "  if (typeof value === \"object\" && {:?} in value) return {{ {:?}: {{ {inner} }} }};",
                    v.json_name, v.json_name
                ));
            }
        }
    }
    l.push(format!(
        "  throw new Error(`Unknown {}: ${{JSON.stringify(value)}}`);",
        e.name
    ));
    l.push("}".into());

    l.join("\n")
}

fn render_enum_internal(e: &EnumInfo, tag: &str) -> String {
    // Minimal internally-tagged support: struct/unit variants keyed by `tag`.
    let mut l = Vec::new();
    l.push(format!("export type {} =", e.name));
    for (i, v) in e.variants.iter().enumerate() {
        let fields = match &v.kind {
            VariantKind::Struct { fields } => fields
                .iter()
                .filter(|f| !f.skip)
                .map(|f| format!("; {}: {}", f.ts_name, f.ts_type))
                .collect::<String>(),
            _ => String::new(),
        };
        let term = if i + 1 == e.variants.len() { ";" } else { "" };
        l.push(format!("  | {{ {tag}: {:?}{fields} }}{term}", v.json_name));
    }
    // decode/encode: identity is correct for internally-tagged with primitive fields.
    l.push(String::new());
    l.push(format!(
        "export function decode{}(json: any): {} {{ return json as {}; }}",
        e.name, e.name, e.name
    ));
    l.push(format!(
        "export function encode{}(value: {}): any {{ return value; }}",
        e.name, e.name
    ));
    l.join("\n")
}

/// Render the client class for `module`, importing DTOs from `dtos_import` and the runtime from
/// `runtime_import`.
pub fn render_client(module: &RpcModuleInfo, dtos_import: &str, runtime_import: &str) -> String {
    let class = format!("{}Client", module.trait_name);
    let mut l = vec![
        GENERATED_BANNER.to_string(),
        "/* eslint-disable */".to_string(),
        format!("// Source trait: {}", module.trait_name),
        String::new(),
        format!(
            "import type {{ AllexTransport, AllexResult, AllexStep }} from {runtime_import:?};"
        ),
    ];

    // Import every DTO type + codec referenced.
    let mut imports = referenced_type_names(module);
    imports.sort();
    imports.dedup();
    if !imports.is_empty() {
        let mut names: Vec<String> = Vec::new();
        for t in &imports {
            names.push(format!("type {t}"));
            names.push(format!("decode{t}"));
            names.push(format!("encode{t}"));
        }
        l.push(format!(
            "import {{ {} }} from {dtos_import:?};",
            names.join(", ")
        ));
    }
    l.push(String::new());
    l.push(format!(
        "/** Generated client for the `{}` module. */",
        module.module_name
    ));
    l.push(format!("export class {class} {{"));
    // Explicit field + assignment (not a TS parameter property) so the output runs under
    // `node --experimental-strip-types` with no build step.
    l.push("  private readonly transport: AllexTransport;".into());
    l.push("  constructor(transport: AllexTransport) {".into());
    l.push("    this.transport = transport;".into());
    l.push("  }".into());

    for m in &module.methods {
        l.push(String::new());
        if m.is_public {
            l.push("  /** Public — no authentication required. */".into());
        } else if !m.allowed_roles.is_empty() {
            l.push(format!(
                "  /** Requires role: {}. */",
                m.allowed_roles.join(", ")
            ));
        }
        let enc_req = format!("encode{}(request)", m.request_type);
        match &m.kind {
            MethodKind::Unary { success, error } => {
                l.push(format!(
                    "  {}(request: {}): Promise<AllexResult<{}, {}>> {{",
                    m.ts_name, m.request_type, success.ts_type, error.ts_type
                ));
                l.push("    return this.transport.callUnary({".into());
                l.push(format!("      module: {:?},", module.module_name));
                l.push(format!("      method: {:?},", m.rust_name));
                l.push(format!("      request: {enc_req},"));
                l.push(format!(
                    "      decode: (json) => {},",
                    success.decode_expr("json")
                ));
                l.push(format!(
                    "      decodeError: (json) => {},",
                    error.decode_expr("json")
                ));
                l.push("    });".into());
                l.push("  }".into());
            }
            MethodKind::Streaming {
                progress,
                success,
                error,
            } => {
                l.push(format!(
                    "  {}(request: {}): AsyncGenerator<AllexStep<{}, {}, {}>> {{",
                    m.ts_name, m.request_type, progress.ts_type, success.ts_type, error.ts_type
                ));
                l.push("    return this.transport.callStreaming({".into());
                l.push(format!("      module: {:?},", module.module_name));
                l.push(format!("      method: {:?},", m.rust_name));
                l.push(format!("      request: {enc_req},"));
                l.push(format!(
                    "      decodeProgress: (json) => {},",
                    progress.decode_expr("json")
                ));
                l.push(format!(
                    "      decodeSuccess: (json) => {},",
                    success.decode_expr("json")
                ));
                l.push(format!(
                    "      decodeError: (json) => {},",
                    error.decode_expr("json")
                ));
                l.push("    });".into());
                l.push("  }".into());
            }
        }
    }
    l.push("}".into());
    l.join("\n") + "\n"
}

// ===========================================================================
// Rust syn::Type → TsType
// ===========================================================================

fn rust_type_to_ts(ty: &Type) -> TsType {
    match ty {
        Type::Path(tp) => {
            let Some(seg) = tp.path.segments.last() else {
                return TsType::Unknown("?".into());
            };
            let ident = seg.ident.to_string();
            let first_arg = || match &seg.arguments {
                PathArguments::AngleBracketed(args) => args.args.iter().find_map(|a| match a {
                    GenericArgument::Type(t) => Some(t),
                    _ => None,
                }),
                _ => None,
            };
            match ident.as_str() {
                "i8" | "i16" | "i32" | "i64" | "i128" | "u8" | "u16" | "u32" | "u64" | "u128"
                | "usize" | "isize" | "f32" | "f64" => TsType::Number,
                "bool" => TsType::Bool,
                "String" | "str" => TsType::Str,
                "Infallible" | "Never" => TsType::Never,
                "Value" | "JsonValue" => TsType::Json,
                "Option" => TsType::Nullable(Box::new(
                    first_arg().map(rust_type_to_ts).unwrap_or(TsType::Json),
                )),
                "Vec" => TsType::List(Box::new(
                    first_arg().map(rust_type_to_ts).unwrap_or(TsType::Json),
                )),
                "HashMap" | "BTreeMap" | "IndexMap" => {
                    // Value type is the 2nd arg.
                    let val = match &seg.arguments {
                        PathArguments::AngleBracketed(args) => args
                            .args
                            .iter()
                            .filter_map(|a| match a {
                                GenericArgument::Type(t) => Some(rust_type_to_ts(t)),
                                _ => None,
                            })
                            .nth(1)
                            .unwrap_or(TsType::Json),
                        _ => TsType::Json,
                    };
                    TsType::Record(Box::new(val))
                }
                _ => TsType::Custom(ident),
            }
        }
        Type::Reference(r) => rust_type_to_ts(&r.elem),
        _ => TsType::Unknown("?".into()),
    }
}

