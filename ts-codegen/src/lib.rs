//! Parses Rust source files, finds every `#[rpc_module]` trait and every serialisable
//! struct/enum, and renders a TypeScript client class + DTO types & codecs.
//!
//! The TypeScript sibling of `allex-dart-codegen`: same parsing model, same wire semantics,
//! TS output instead of Dart. DTO interfaces use camelCase property names; the generated
//! `encode*`/`decode*` functions remap to/from the serde JSON wire keys, so the wire format is
//! identical to the Rust/Dart clients.

use std::collections::{HashSet, VecDeque};
use syn::{
    Attribute, Fields, FnArg, GenericArgument, ItemEnum, ItemStruct, ItemTrait, LitStr, PatType,
    PathArguments, ReturnType, TraitItem, TraitItemFn, Type, TypeParamBound,
};

pub const GENERATED_BANNER: &str = "// GENERATED by `allex-ts-codegen` — do not edit by hand.";

// ===========================================================================
// RPC model
// ===========================================================================

/// One `#[rpc_module]` trait.
pub struct RpcModuleInfo {
    /// Rust trait name, e.g. `HealthV1`.
    pub trait_name: String,
    /// Wire module name, e.g. `health_v_1`.
    pub module_name: String,
    pub methods: Vec<MethodInfo>,
}

pub struct MethodInfo {
    /// Rust/wire method name, e.g. `count_up`.
    pub rust_name: String,
    /// TS method identifier (camelCase), e.g. `countUp`.
    pub ts_name: String,
    pub request_type: String,
    pub kind: MethodKind,
    pub is_public: bool,
    pub allowed_roles: Vec<String>,
}

pub enum MethodKind {
    Unary {
        success: TypeRef,
        error: TypeRef,
    },
    Streaming {
        progress: TypeRef,
        success: TypeRef,
        error: TypeRef,
    },
}

/// A referenced type: its TS type string, a decode expression factory, and the custom type
/// names it roots (for reachability).
pub struct TypeRef {
    pub ts_type: String,
    ts: TsType,
    pub root_types: Vec<String>,
}

impl TypeRef {
    fn of(ty: &Type) -> Self {
        let ts = rust_type_to_ts(ty);
        TypeRef {
            ts_type: ts.type_str(),
            root_types: referenced_custom_type_names(ty),
            ts,
        }
    }
    /// Decode expression turning the raw JSON value `src` into this type.
    pub fn decode_expr(&self, src: &str) -> String {
        self.ts.decode(src)
    }
}

// ===========================================================================
// DTO model
// ===========================================================================

pub enum DtoInfo {
    Struct(StructInfo),
    Enum(EnumInfo),
}

impl DtoInfo {
    pub fn name(&self) -> &str {
        match self {
            DtoInfo::Struct(s) => &s.name,
            DtoInfo::Enum(e) => &e.name,
        }
    }
}

pub struct StructInfo {
    pub name: String,
    pub fields: Vec<FieldInfo>,
}

pub struct FieldInfo {
    /// TS property identifier (camelCase).
    pub ts_name: String,
    /// serde JSON wire key.
    pub json_name: String,
    ts: TsType,
    pub ts_type: String,
    pub skip: bool,
}

pub struct EnumInfo {
    pub name: String,
    pub repr: EnumRepr,
    pub variants: Vec<VariantInfo>,
}

pub enum EnumRepr {
    /// Default serde: unit → JSON string, newtype/struct → `{"Name": payload}`.
    External,
    /// `#[serde(tag = "...")]`
    Internal { tag: String },
}

pub struct VariantInfo {
    pub json_name: String,
    pub kind: VariantKind,
}

pub enum VariantKind {
    Unit,
    Newtype { ts: TsType, ts_type: String },
    Struct { fields: Vec<FieldInfo> },
}

// ===========================================================================
// TS type representation
// ===========================================================================

#[derive(Clone)]
pub enum TsType {
    Number,
    Bool,
    Str,
    Never,
    /// `serde_json::Value` — arbitrary JSON, `unknown` in TS.
    Json,
    Nullable(Box<TsType>),
    List(Box<TsType>),
    Record(Box<TsType>),
    Custom(String),
    Unknown(String),
}

impl TsType {
    pub fn type_str(&self) -> String {
        match self {
            TsType::Number => "number".into(),
            TsType::Bool => "boolean".into(),
            TsType::Str => "string".into(),
            TsType::Never => "never".into(),
            TsType::Json => "unknown".into(),
            TsType::Nullable(inner) => format!("{} | null", inner.type_str()),
            TsType::List(elem) => format!("Array<{}>", elem.type_str()),
            TsType::Record(val) => format!("Record<string, {}>", val.type_str()),
            TsType::Custom(name) => name.clone(),
            TsType::Unknown(_) => "unknown".into(),
        }
    }

    /// Expression decoding raw JSON `src` (typed `any`) into this type.
    fn decode(&self, src: &str) -> String {
        match self {
            TsType::Number => format!("{src} as number"),
            TsType::Bool => format!("{src} as boolean"),
            TsType::Str => format!("{src} as string"),
            TsType::Never => "(() => { throw new Error('unreachable: never'); })()".into(),
            TsType::Json => src.to_string(),
            TsType::Unknown(_) => src.to_string(),
            TsType::Nullable(inner) => {
                format!("({src} == null ? null : {})", inner.decode(src))
            }
            TsType::List(elem) => {
                let e = elem.decode("e");
                if e == "e" {
                    format!("({src} as unknown[])")
                } else {
                    format!("({src} as unknown[]).map((e) => {e})")
                }
            }
            TsType::Record(val) => {
                let v = val.decode("v");
                if v == "v" {
                    format!("({src} as Record<string, unknown>)")
                } else {
                    format!(
                        "Object.fromEntries(Object.entries({src} as Record<string, unknown>).map(([k, v]) => [k, {v}]))"
                    )
                }
            }
            TsType::Custom(name) => format!("decode{name}({src})"),
        }
    }

    /// Expression encoding a TS value `val` of this type into JSON.
    fn encode(&self, val: &str) -> String {
        match self {
            TsType::Number | TsType::Bool | TsType::Str | TsType::Json | TsType::Unknown(_) => {
                val.to_string()
            }
            TsType::Never => "(() => { throw new Error('unreachable: never'); })()".into(),
            TsType::Nullable(inner) => {
                let e = inner.encode(val);
                if e == val {
                    val.to_string()
                } else {
                    format!("({val} == null ? null : {e})")
                }
            }
            TsType::List(elem) => {
                let e = elem.encode("e");
                if e == "e" {
                    val.to_string()
                } else {
                    format!("{val}.map((e) => {e})")
                }
            }
            TsType::Record(v_ty) => {
                let e = v_ty.encode("v");
                if e == "v" {
                    val.to_string()
                } else {
                    format!("Object.fromEntries(Object.entries({val}).map(([k, v]) => [k, {e}]))")
                }
            }
            TsType::Custom(name) => format!("encode{name}({val})"),
        }
    }
}

// ===========================================================================
// serde attribute parsing
// ===========================================================================

#[derive(Default)]
struct SerdeAttrs {
    rename_all: Option<String>,
    rename: Option<String>,
    skip: bool,
    tag: Option<String>,
}

fn parse_serde_attrs(attrs: &[Attribute]) -> SerdeAttrs {
    let mut out = SerdeAttrs::default();
    for attr in attrs {
        if !attr.path().is_ident("serde") {
            continue;
        }
        let _ = attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("rename_all") {
                out.rename_all = Some(meta.value()?.parse::<LitStr>()?.value());
            } else if meta.path.is_ident("rename") {
                out.rename = Some(meta.value()?.parse::<LitStr>()?.value());
            } else if meta.path.is_ident("tag") {
                out.tag = Some(meta.value()?.parse::<LitStr>()?.value());
            } else if meta.path.is_ident("skip")
                || meta.path.is_ident("skip_serializing")
                || meta.path.is_ident("skip_deserializing")
            {
                out.skip = true;
            } else if meta.input.peek(syn::Token![=]) {
                let _: syn::Expr = meta.value()?.parse()?;
            }
            Ok(())
        });
    }
    out
}

