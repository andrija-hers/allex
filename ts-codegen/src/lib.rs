fn has_derive(attrs: &[Attribute], name: &str) -> bool {
    attrs.iter().any(|attr| {
        if !attr.path().is_ident("derive") {
            return false;
        }
        let mut found = false;
        let _ = attr.parse_nested_meta(|meta| {
            if meta.path.segments.last().map(|s| s.ident == name) == Some(true) {
                found = true;
            }
            Ok(())
        });
        found
    })
}

fn is_serializable(attrs: &[Attribute]) -> bool {
    has_derive(attrs, "Serialize") || has_derive(attrs, "Deserialize")
}

fn extract_struct(item: &ItemStruct) -> Option<DtoInfo> {
    if !is_serializable(&item.attrs) {
        return None;
    }
    let Fields::Named(named) = &item.fields else {
        return None;
    };
    let serde = parse_serde_attrs(&item.attrs);
    let fields = named
        .named
        .iter()
        .filter_map(|f| extract_field(f, serde.rename_all.as_deref()))
        .collect();
    Some(DtoInfo::Struct(StructInfo {
        name: item.ident.to_string(),
        fields,
    }))
}

fn extract_field(field: &syn::Field, rename_all: Option<&str>) -> Option<FieldInfo> {
    let rust_name = field.ident.as_ref()?.to_string();
    let serde = parse_serde_attrs(&field.attrs);
    let json_name = serde
        .rename
        .clone()
        .unwrap_or_else(|| apply_rename_all(&rust_name, rename_all));
    let ts = rust_type_to_ts(&field.ty);
    Some(FieldInfo {
        ts_name: snake_to_camel(&rust_name),
        json_name,
        ts_type: ts.type_str(),
        ts,
        skip: serde.skip,
    })
}

fn extract_enum(item: &ItemEnum) -> Option<DtoInfo> {
    if !is_serializable(&item.attrs) {
        return None;
    }
    let serde = parse_serde_attrs(&item.attrs);
    let repr = match serde.tag {
        Some(tag) => EnumRepr::Internal { tag },
        None => EnumRepr::External,
    };
    let variants = item
        .variants
        .iter()
        .filter_map(|v| extract_variant(v, serde.rename_all.as_deref()))
        .collect();
    Some(DtoInfo::Enum(EnumInfo {
        name: item.ident.to_string(),
        repr,
        variants,
    }))
}

fn extract_variant(variant: &syn::Variant, rename_all: Option<&str>) -> Option<VariantInfo> {
    let serde = parse_serde_attrs(&variant.attrs);
    if serde.skip {
        return None;
    }
    let json_name = serde
        .rename
        .unwrap_or_else(|| apply_rename_all(&variant.ident.to_string(), rename_all));
    let kind = match &variant.fields {
        Fields::Unit => VariantKind::Unit,
        Fields::Unnamed(u) if u.unnamed.len() == 1 => {
            let ts = rust_type_to_ts(&u.unnamed[0].ty);
            VariantKind::Newtype {
                ts_type: ts.type_str(),
                ts,
            }
        }
        Fields::Named(named) => VariantKind::Struct {
            fields: named
                .named
                .iter()
                .filter_map(|f| extract_field(f, rename_all))
                .collect(),
        },
        _ => return None,
    };
    Some(VariantInfo { json_name, kind })
}

fn reachable_from_dto(dto: &DtoInfo) -> Vec<String> {
    let mut out = Vec::new();
    let mut push = |t: &TsType| collect_custom_from_ts(t, &mut out);
    match dto {
        DtoInfo::Struct(s) => s
            .fields
            .iter()
            .filter(|f| !f.skip)
            .for_each(|f| push(&f.ts)),
        DtoInfo::Enum(e) => {
            for v in &e.variants {
                match &v.kind {
                    VariantKind::Newtype { ts, .. } => push(ts),
                    VariantKind::Struct { fields } => {
                        fields.iter().filter(|f| !f.skip).for_each(|f| push(&f.ts))
                    }
                    VariantKind::Unit => {}
                }
            }
        }
    }
    out
}

fn collect_custom_from_ts(ts: &TsType, out: &mut Vec<String>) {
    match ts {
        TsType::Custom(name) => {
            if !out.contains(name) {
                out.push(name.clone());
            }
        }
        TsType::Nullable(inner) | TsType::List(inner) | TsType::Record(inner) => {
            collect_custom_from_ts(inner, out)
        }
        _ => {}
    }
}

