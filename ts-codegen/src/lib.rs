/// PascalCase trait name → allex wire snake_case module name (the `rpc_macro` algorithm).
fn module_name_from_trait(ident: &str) -> String {
    let mut out = String::new();
    let chars: Vec<char> = ident.chars().collect();
    for (i, &ch) in chars.iter().enumerate() {
        if ch.is_ascii_uppercase() {
            if i > 0 {
                let prev = chars[i - 1];
                if prev.is_ascii_lowercase()
                    || prev.is_ascii_digit()
                    || (prev.is_ascii_uppercase()
                        && chars.get(i + 1).is_some_and(|&n| n.is_ascii_lowercase()))
                {
                    out.push('_');
                }
            }
            out.push(ch.to_ascii_lowercase());
        } else if ch.is_ascii_digit() {
            if i > 0 && chars[i - 1].is_ascii_alphabetic() {
                out.push('_');
            }
            out.push(ch);
        } else {
            out.push(ch);
        }
    }
    out
}

fn snake_to_camel(s: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for ch in s.chars() {
        if ch == '_' {
            upper = true;
        } else if upper {
            out.extend(ch.to_uppercase());
            upper = false;
        } else {
            out.push(ch);
        }
    }
    out
}

fn apply_rename_all(name: &str, rename_all: Option<&str>) -> String {
    match rename_all {
        Some("camelCase") => snake_to_camel(name),
        Some("snake_case") | None => name.to_string(),
        Some("PascalCase") => {
            let camel = snake_to_camel(name);
            let mut c = camel.chars();
            match c.next() {
                Some(first) => first.to_uppercase().chain(c).collect(),
                None => camel,
            }
        }
        Some("SCREAMING_SNAKE_CASE") => name.to_uppercase(),
        Some("kebab-case") => name.replace('_', "-"),
        // Unknown convention: leave as-is.
        Some(_) => name.to_string(),
    }
}
