/// Parse Rust source and return every `#[rpc_module]` trait.
pub fn find_rpc_modules(source: &str) -> Vec<RpcModuleInfo> {
    let file = match syn::parse_file(source) {
        Ok(f) => f,
        Err(e) => {
            eprintln!("Warning: failed to parse source: {e}");
            return Vec::new();
        }
    };
    file.items
        .iter()
        .filter_map(|item| match item {
            syn::Item::Trait(t) if has_attr(&t.attrs, "rpc_module") => extract_module_info(t),
            _ => None,
        })
        .collect()
}

/// Every custom type name referenced by a module's method signatures.
pub fn referenced_type_names(module: &RpcModuleInfo) -> Vec<String> {
    let mut names: Vec<String> = module
        .methods
        .iter()
        .flat_map(|m| {
            let mut v = vec![m.request_type.clone()];
            match &m.kind {
                MethodKind::Unary { success, error } => {
                    v.extend(success.root_types.iter().cloned());
                    v.extend(error.root_types.iter().cloned());
                }
                MethodKind::Streaming {
                    progress,
                    success,
                    error,
                } => {
                    v.extend(progress.root_types.iter().cloned());
                    v.extend(success.root_types.iter().cloned());
                    v.extend(error.root_types.iter().cloned());
                }
            }
            v
        })
        .collect();
    names.sort();
    names.dedup();
    names
}

/// Parse Rust source and return all serialisable struct/enum definitions.
pub fn find_dto_types(source: &str) -> Vec<DtoInfo> {
    let file = match syn::parse_file(source) {
        Ok(f) => f,
        Err(e) => {
            eprintln!("Warning: failed to parse source for DTOs: {e}");
            return Vec::new();
        }
    };
    file.items
        .iter()
        .filter_map(|item| match item {
            syn::Item::Struct(s) => extract_struct(s),
            syn::Item::Enum(e) => extract_enum(e),
            _ => None,
        })
        .collect()
}

/// The reachable subset of DTOs starting from `roots`, following field types transitively.
pub fn find_reachable_dtos(source: &str, roots: &[&str]) -> Vec<DtoInfo> {
    reachable_dtos(find_dto_types(source), roots)
}

/// The reachable subset of an already-collected DTO set starting from `roots`, following field
/// types transitively. Use this when the DTOs come from several source files (each parsed
/// independently — a plain text concatenation of Rust files is not itself valid Rust, e.g. a
/// second file's `//!` inner-doc header would land mid-stream). Duplicate definitions (same name)
/// are collapsed to the first.
pub fn reachable_dtos(all: Vec<DtoInfo>, roots: &[&str]) -> Vec<DtoInfo> {
    let mut all = all;
    let mut seen_names: HashSet<String> = HashSet::new();
    all.retain(|d| seen_names.insert(d.name().to_string()));

    let index: std::collections::HashMap<&str, usize> =
        all.iter().enumerate().map(|(i, d)| (d.name(), i)).collect();

    let mut visited: HashSet<String> = HashSet::new();
    let mut queue: VecDeque<String> = roots.iter().map(|s| s.to_string()).collect();

    while let Some(name) = queue.pop_front() {
        if !visited.insert(name.clone()) {
            continue;
        }
        if let Some(&idx) = index.get(name.as_str()) {
            for dep in reachable_from_dto(&all[idx]) {
                if !visited.contains(&dep) {
                    queue.push_back(dep);
                }
            }
        }
    }

    all.into_iter()
        .filter(|d| visited.contains(d.name()))
        .collect()
}

