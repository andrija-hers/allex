/// Parse a Rust source file and return every `#[rpc_module]` trait found in it.
pub fn find_rpc_modules(source: &str) -> Vec<RpcModuleInfo> {
    let file = match syn::parse_file(source) {
        Ok(f) => f,
        Err(e) => {
            eprintln!("Warning: failed to parse source: {e}");
            return Vec::new();
        }
    };
    file.items
        .iter()
        .filter_map(|item| {
            if let syn::Item::Trait(t) = item
                && has_attr(&t.attrs, "rpc_module")
            {
                return extract_module_info(t);
            }
            None
        })
        .collect()
}

/// Collect all type names referenced by methods in this module
/// (request types, success/error/progress types).
pub fn referenced_type_names(module: &RpcModuleInfo) -> Vec<String> {
    let mut names: Vec<String> = module
        .methods
        .iter()
        .flat_map(|m| {
            let mut v = vec![m.request_type.clone()];
            match &m.kind {
                MethodKind::Unary {
                    success_type,
                    error_type,
                } => {
                    v.extend(success_type.root_types.iter().cloned());
                    v.extend(error_type.root_types.iter().cloned());
                }
                MethodKind::Streaming {
                    progress_type,
                    success_type,
                    error_type,
                } => {
                    v.extend(progress_type.root_types.iter().cloned());
                    v.extend(success_type.root_types.iter().cloned());
                    v.extend(error_type.root_types.iter().cloned());
                }
            }
            v
        })
        .collect();
    names.sort();
    names.dedup();
    names
}

/// Parse a Rust source file and return all serialisable struct/enum definitions.
pub fn find_dto_types(source: &str) -> Vec<DtoInfo> {
    let file = match syn::parse_file(source) {
        Ok(f) => f,
        Err(e) => {
            eprintln!("Warning: failed to parse source for DTOs: {e}");
            return Vec::new();
        }
    };
    file.items
        .iter()
        .filter_map(|item| match item {
            syn::Item::Struct(s) => extract_struct(s),
            syn::Item::Enum(e) => extract_enum(e),
            _ => None,
        })
        .collect()
}

/// Return the reachable subset of DTOs starting from `roots`, following
/// field types transitively.  Types not found in `source` are treated as
/// external and are not included in the output but are still followed
/// (so their own fields don't prevent discovery of siblings).
///
/// Single-source convenience over [`reachable_dtos`]; for multi-file input parse each file with
/// [`find_dto_types`], concatenate the `Vec<DtoInfo>`s, and call [`reachable_dtos`] directly.
pub fn find_reachable_dtos(source: &str, roots: &[&str]) -> Vec<DtoInfo> {
    reachable_dtos(find_dto_types(source), roots)
}

/// Return the reachable subset of an already-collected DTO list, following field types transitively
/// from `roots`. Use this to resolve DTOs across several files (each parsed independently with
/// [`find_dto_types`]) — the correct multi-file strategy, since a plain text concatenation of Rust
/// files is not valid Rust (a non-first file's `//!`/`#![…]` header is only legal at file start).
pub fn reachable_dtos(all: Vec<DtoInfo>, roots: &[&str]) -> Vec<DtoInfo> {
    let index: std::collections::HashMap<&str, usize> =
        all.iter().enumerate().map(|(i, d)| (d.name(), i)).collect();

    let mut visited: HashSet<String> = HashSet::new();
    let mut queue: VecDeque<String> = roots.iter().map(|s| s.to_string()).collect();

    while let Some(name) = queue.pop_front() {
        if visited.contains(&name) {
            continue;
        }
        visited.insert(name.clone());
        if let Some(&idx) = index.get(name.as_str()) {
            for dep in reachable_from_dto(&all[idx]) {
                if !visited.contains(&dep) {
                    queue.push_back(dep);
                }
            }
        }
    }

    // Return in original definition order.
    all.into_iter()
        .filter(|d| visited.contains(d.name()))
        .collect()
}

/// Render a Dart client class for the given module.
/// Imports `{module_name}_dtos.dart` from the same directory.
pub fn render_dart_client(module: &RpcModuleInfo) -> String {
    render_dart_client_importing(module, &format!("{}_dtos.dart", module.module_name))
}

/// Render a Dart client class importing its DTOs from `dtos_import` (a file basename in the
/// same directory). Pass a shared file (e.g. `dtos.dart`) when several modules share DTO types,
/// so an application can import multiple generated clients without duplicate-definition clashes.
pub fn render_dart_client_importing(module: &RpcModuleInfo, dtos_import: &str) -> String {
    let class_name = format!("{}Client", module.trait_name);
    let mut lines: Vec<String> = vec![
        GENERATED_BANNER.into(),
        format!("// Source trait: {}", module.trait_name),
        String::new(),
        "// ignore_for_file: lines_longer_than_80_chars, no_leading_underscores_for_local_identifiers".into(),
        String::new(),
        "import 'package:allex/allex.dart';".into(),
        format!("import '{dtos_import}';"),
        String::new(),
        format!("/// Generated Dart client for [{}].", module.trait_name),
        format!("class {class_name} {{"),
        "  final AllexTransport transport;".into(),
        format!("  const {class_name}(this.transport);"),
    ];

    for method in &module.methods {
        lines.push(String::new());
        if method.is_public {
            lines.push("  /// Public — no authentication required.".into());
        } else if !method.allowed_roles.is_empty() {
            lines.push(format!(
                "  /// Requires role: {}",
                method.allowed_roles.join(", ")
            ));
        } else {
            lines.push("  /// Requires authentication.".into());
        }

        match &method.kind {
            MethodKind::Unary {
                success_type,
                error_type,
            } => {
                lines.push(format!(
                    "  Future<AllexResult<{}, {}>> {}(",
                    success_type.dart_type, error_type.dart_type, method.dart_name,
                ));
                lines.push(format!("    {} request,", method.request_type));
                lines.push("  ) =>".into());
                lines.push("    transport.callUnary(".into());
                lines.push(format!("      module: '{}',", module.module_name));
                lines.push(format!("      method: '{}',", method.rust_name));
                lines.push("      request: request.toJson(),".into());
                lines.push(format!(
                    "      decode: (json) => {},",
                    success_type.decode_expr
                ));
                lines.push(format!(
                    "      decodeError: (json) => {},",
                    error_type.decode_expr
                ));
                lines.push("    );".into());
            }
            MethodKind::Streaming {
                progress_type,
                success_type,
                error_type,
            } => {
                lines.push(format!(
                    "  Stream<AllexStep<{}, {}, {}>> {}(",
                    progress_type.dart_type,
                    success_type.dart_type,
                    error_type.dart_type,
                    method.dart_name,
                ));
                lines.push(format!("    {} request,", method.request_type));
                lines.push("  ) =>".into());
                lines.push("    transport.callStreaming(".into());
                lines.push(format!("      module: '{}',", module.module_name));
                lines.push(format!("      method: '{}',", method.rust_name));
                lines.push("      request: request.toJson(),".into());
                lines.push(format!(
                    "      decodeProgress: (json) => {},",
                    progress_type.decode_expr
                ));
                lines.push(format!(
                    "      decodeSuccess: (json) => {},",
                    success_type.decode_expr
                ));
                lines.push(format!(
                    "      decodeError: (json) => {},",
                    error_type.decode_expr
                ));
                lines.push("    );".into());
            }
        }
    }
    lines.push("}".into());
    lines.join("\n") + "\n"
}

/// Render a complete Dart file containing DTO classes for `dtos`.
/// `extra_imports` are injected for types that come from outside the
/// source file (hand-written models, other generated files, etc.).
pub fn render_dart_dtos(module_name: &str, dtos: &[DtoInfo], extra_imports: &[&str]) -> String {
    let mut lines: Vec<String> = vec![
        GENERATED_BANNER.into(),
        format!("// DTOs for module: {module_name}"),
        String::new(),
        "// ignore_for_file: lines_longer_than_80_chars, no_leading_underscores_for_local_identifiers".into(),
    ];

    if !extra_imports.is_empty() {
        lines.push(String::new());
        for imp in extra_imports {
            lines.push(format!("import '{imp}';"));
        }
    }

    for dto in dtos {
        lines.push(String::new());
        lines.push(render_dto(dto));
    }

    lines.join("\n") + "\n"
}

