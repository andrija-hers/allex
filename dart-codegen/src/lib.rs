// Internal: serde attribute parsing
// ===========================================================================

#[derive(Default)]
struct SerdeAttrs {
    rename_all: Option<String>,
    rename: Option<String>,
    skip: bool,
    has_default: bool,
    tag: Option<String>,
    untagged: bool,
    flatten: bool,
}

fn parse_serde_attrs(attrs: &[Attribute]) -> SerdeAttrs {
    let mut out = SerdeAttrs::default();
    for attr in attrs {
        if !attr.path().is_ident("serde") {
            continue;
        }
        let _ = attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("rename_all") {
                let v = meta.value()?;
                let s: LitStr = v.parse()?;
                out.rename_all = Some(s.value());
            } else if meta.path.is_ident("rename") {
                let v = meta.value()?;
                let s: LitStr = v.parse()?;
                out.rename = Some(s.value());
            } else if meta.path.is_ident("tag") {
                let v = meta.value()?;
                let s: LitStr = v.parse()?;
                out.tag = Some(s.value());
            } else if meta.path.is_ident("skip")
                || meta.path.is_ident("skip_serializing")
                || meta.path.is_ident("skip_deserializing")
            {
                out.skip = true;
            } else if meta.path.is_ident("default") {
                out.has_default = true;
            } else if meta.path.is_ident("untagged") {
                out.untagged = true;
            } else if meta.path.is_ident("flatten") {
                out.flatten = true;
            } else {
                // Unknown serde attr — consume any `= <expr>` to avoid parse errors.
                if meta.input.peek(syn::Token![=]) {
                    let _: syn::Expr = meta.value()?.parse()?;
                }
            }
            Ok(())
        });
    }
    out
}

