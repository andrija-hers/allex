//! Generates a **Dart client + DTO types** from Rust `#[rpc_module]` source — wire-compatible with
//! the Rust and TypeScript clients.
//!
//! # How it works: parse source, not macro output
//!
//! This crate reads Rust *source text* with `syn` — it never runs the `#[rpc_module]` proc-macro or
//! compiles the crate — and re-derives the same contract from the syntax. [`find_rpc_modules`]
//! locates every `#[rpc_module]` trait; [`find_reachable_dtos`] collects **only** the structs/enums
//! actually reachable from those methods' signatures (not every type in the file); then
//! [`render_dart_client`] and [`render_dart_dtos`] emit the code. Pass one or more `--source` files
//! — they're parsed independently and merged, so DTOs may live across files.
//!
//! # The wire stays identical across languages
//!
//! Generated Dart uses idiomatic names, but its encode/decode remaps to the exact serde JSON wire
//! keys — honoring `#[serde(rename_all = ..)]` on **both struct fields and enum variants** — and
//! targets the same `foo_v_1`-style module name the Rust server registers. So the Dart, TypeScript
//! (`allex-ts-codegen`), and Rust clients all speak the same bytes. Output starts with
//! [`GENERATED_BANNER`]; regenerate rather than hand-edit.

use std::collections::{HashSet, VecDeque};
use syn::{
    AngleBracketedGenericArguments, Attribute, Fields, FnArg, GenericArgument, ItemEnum,
    ItemStruct, ItemTrait, LitStr, PatType, PathArguments, ReturnType, TraitItem, TraitItemFn,
    Type, TypeParamBound,
};

pub const GENERATED_BANNER: &str = "// GENERATED by `cargo run -p allex-dart-codegen -- --source <rust-file> [--source <rust-file> ...] --out-dir <dart-dir>` — do not edit manually.";

// ===========================================================================
// Public RPC model (unchanged)
// ===========================================================================

/// All information extracted from one `#[rpc_module]` trait.
pub struct RpcModuleInfo {
    /// Original Rust trait name, e.g. `ActiveSchedulesV1`.
    pub trait_name: String,
    /// Wire module name, e.g. `active_schedules_v_1`.
    pub module_name: String,
    pub methods: Vec<MethodInfo>,
}

pub struct MethodInfo {
    pub rust_name: String,
    pub dart_name: String,
    pub request_type: String,
    pub kind: MethodKind,
    pub is_public: bool,
    pub allowed_roles: Vec<String>,
}

pub enum MethodKind {
    Unary {
        success_type: RpcTypeInfo,
        error_type: RpcTypeInfo,
    },
    Streaming {
        progress_type: RpcTypeInfo,
        success_type: RpcTypeInfo,
        error_type: RpcTypeInfo,
    },
}

pub struct RpcTypeInfo {
    pub dart_type: String,
    pub decode_expr: String,
    pub root_types: Vec<String>,
}

// ===========================================================================
// Public DTO model
// ===========================================================================

pub enum DtoInfo {
    Struct(StructInfo),
    Enum(EnumInfo),
}

pub struct StructInfo {
    pub name: String,
    pub fields: Vec<FieldInfo>,
}

/// A single field in a struct (or a struct-variant of an enum).
pub struct FieldInfo {
    /// Dart identifier (camelCase).
    pub dart_name: String,
    /// JSON key as serde would produce it.
    pub json_name: String,
    /// Dart type string, e.g. `"int?"`, `"List<Bar>"`.
    pub dart_type: String,
    /// True when the Rust type is `Option<T>`.
    pub is_optional: bool,
    pub skip: bool,
    /// `#[serde(default)]`: the field may be absent from the wire and is filled
    /// with its type's default on decode.
    pub has_default: bool,
    /// `#[serde(flatten)]`: the field has no JSON key of its own. A flattened
    /// struct reads/writes its fields at the parent's level; a flattened map
    /// captures every key not consumed by the parent's named fields.
    pub flatten: bool,
}

pub struct EnumInfo {
    pub name: String,
    pub repr: EnumRepr,
    pub variants: Vec<VariantInfo>,
}

pub enum EnumRepr {
    /// Default serde representation: unit variants → JSON string,
    /// newtype/struct variants → `{"Name": payload}`.
    External,
    /// `#[serde(tag = "type")]`
    Internal { tag: String },
    /// `#[serde(untagged)]`
    Untagged,
}

pub struct VariantInfo {
    /// Wire name (after rename/rename_all).
    pub json_name: String,
    /// Suffix appended to the parent enum name for the Dart class,
    /// e.g. `"Overflow"` → Dart class `ArithmeticErrorOverflow`.
    pub dart_suffix: String,
    pub kind: VariantKind,
}

pub enum VariantKind {
    Unit,
    Newtype { dart_type: String },
    Struct { fields: Vec<FieldInfo> },
}

impl DtoInfo {
    pub fn name(&self) -> &str {
        match self {
            DtoInfo::Struct(s) => &s.name,
            DtoInfo::Enum(e) => &e.name,
        }
    }
}

// ===========================================================================
// Internal: Dart type representation
// ===========================================================================

#[derive(Clone)]
enum DartType {
    Int,
    Double,
    Bool,
    DartString,
    Never,
    /// `serde_json::Value` — an arbitrary JSON value, `dynamic` in Dart.
    Json,
    Nullable(Box<DartType>),
    List(Box<DartType>),
    Map(Box<DartType>, Box<DartType>),
    Custom(String),
    Unknown(String),
}

impl DartType {
    fn type_str(&self) -> String {
        match self {
            DartType::Int => "int".into(),
            DartType::Double => "double".into(),
            DartType::Bool => "bool".into(),
            DartType::DartString => "String".into(),
            DartType::Nullable(inner) => format!("{}?", inner.type_str()),
            DartType::List(elem) => format!("List<{}>", elem.type_str()),
            DartType::Map(k, v) => format!("Map<{}, {}>", k.type_str(), v.type_str()),
            DartType::Custom(name) => name.clone(),
            DartType::Never => "Never".into(),
            DartType::Json => "dynamic".into(),
            DartType::Unknown(name) => format!("dynamic /* {name} */"),
        }
    }

    /// Expression that decodes a `dynamic` Dart value `src` into this type.
    fn decode(&self, src: &str) -> String {
        match self {
            DartType::Int => format!("({src} as num).toInt()"),
            DartType::Double => format!("({src} as num).toDouble()"),
            DartType::Bool => format!("{src} as bool"),
            DartType::DartString => format!("{src} as String"),
            DartType::Nullable(inner) => match inner.as_ref() {
                DartType::Int => format!("({src} as num?)?.toInt()"),
                DartType::Double => format!("({src} as num?)?.toDouble()"),
                DartType::Bool => format!("{src} as bool?"),
                DartType::DartString => format!("{src} as String?"),
                inner => {
                    let inner_dec = inner.decode(src);
                    format!("{src} == null ? null : {inner_dec}")
                }
            },
            DartType::List(elem) => {
                let elem_dec = elem.decode("_e");
                format!("({src} as List).map((_e) => {elem_dec}).toList()")
            }
            DartType::Map(_, val) => {
                let val_dec = val.decode("_v");
                format!("({src} as Map<String, dynamic>).map((_k, _v) => MapEntry(_k, {val_dec}))")
            }
            DartType::Custom(name) => format!("{name}.fromJson({src})"),
            DartType::Never => "throw UnimplementedError('unreachable: Never')".to_string(),
            DartType::Json | DartType::Unknown(_) => src.to_string(),
        }
    }

    /// Expression that encodes a Dart value `val` of this type to JSON.
    fn encode(&self, val: &str) -> String {
        match self {
            DartType::Int | DartType::Double | DartType::Bool | DartType::DartString => {
                val.to_string()
            }
            DartType::Nullable(inner) => match inner.as_ref() {
                DartType::Int | DartType::Double | DartType::Bool | DartType::DartString => {
                    val.to_string()
                }
                DartType::Custom(_) => format!("{val}?.toJson()"),
                inner => {
                    let inner_enc = inner.encode(&format!("{val}!"));
                    format!("{val} == null ? null : {inner_enc}")
                }
            },
            DartType::List(elem) => {
                let elem_enc = elem.encode("_e");
                if elem_enc == "_e" {
                    val.to_string()
                } else {
                    format!("{val}.map((_e) => {elem_enc}).toList()")
                }
            }
            DartType::Map(_, v_ty) => {
                let v_enc = v_ty.encode("_v");
                if v_enc == "_v" {
                    val.to_string()
                } else {
                    format!("{val}.map((_k, _v) => MapEntry(_k, {v_enc}))")
                }
            }
            DartType::Never => "throw UnimplementedError('unreachable: Never')".to_string(),
            DartType::Custom(_) => format!("{val}.toJson()"),
            DartType::Json | DartType::Unknown(_) => val.to_string(),
        }
    }

    fn is_nullable(&self) -> bool {
        matches!(self, DartType::Nullable(_))
    }

    /// The Dart constant that serde's `#[serde(default)]` fills in when the field is absent, for
    /// the types whose default is expressible as a `const`. Returns `None` for types with no
    /// synthesizable default (custom classes have no zero-arg constructor, `dynamic`/`Never` have
    /// no meaningful one) — such fields stay `required`.
    fn default_literal(&self) -> Option<&'static str> {
        match self {
            DartType::Int => Some("0"),
            DartType::Double => Some("0"),
            DartType::Bool => Some("false"),
            DartType::DartString => Some("''"),
            DartType::List(_) => Some("const []"),
            DartType::Map(..) => Some("const {}"),
            DartType::Nullable(_) => Some("null"),
            DartType::Custom(_) | DartType::Never | DartType::Json | DartType::Unknown(_) => None,
        }
    }
}

