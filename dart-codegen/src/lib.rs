fn extract_module_info(trait_item: &ItemTrait) -> Option<RpcModuleInfo> {
    let trait_name = trait_item.ident.to_string();
    let module_name = module_name_from_trait(&trait_name);
    let methods = trait_item
        .items
        .iter()
        .filter_map(|item| {
            if let TraitItem::Fn(m) = item {
                match extract_method_info(m) {
                    Some(info) => Some(info),
                    None => {
                        eprintln!(
                            "Warning: skipping method `{}` — could not determine kind",
                            m.sig.ident
                        );
                        None
                    }
                }
            } else {
                None
            }
        })
        .collect();
    Some(RpcModuleInfo {
        trait_name,
        module_name,
        methods,
    })
}

fn extract_method_info(method: &TraitItemFn) -> Option<MethodInfo> {
    let rust_name = method.sig.ident.to_string();
    let dart_name = snake_to_camel(&rust_name);
    let request_type = extract_request_type_name(method)?;
    let kind = extract_method_kind(method)?;
    let (is_public, allowed_roles) = extract_roles(&method.attrs);
    Some(MethodInfo {
        rust_name,
        dart_name,
        request_type,
        kind,
        is_public,
        allowed_roles,
    })
}

fn extract_request_type_name(method: &TraitItemFn) -> Option<String> {
    method
        .sig
        .inputs
        .iter()
        .filter_map(|input| match input {
            FnArg::Typed(PatType { ty, .. }) => Some(type_ident(ty)),
            FnArg::Receiver(_) => None,
        })
        .next()
}

fn extract_method_kind(method: &TraitItemFn) -> Option<MethodKind> {
    let return_ty = match &method.sig.output {
        ReturnType::Type(_, ty) => ty.as_ref(),
        ReturnType::Default => return None,
    };

    if method.sig.asyncness.is_some() {
        let (s, e) = extract_result_types(return_ty)?;
        return Some(MethodKind::Unary {
            success_type: s,
            error_type: e,
        });
    }

    if let Some(types) = path_type_args(return_ty, "ProgressableFuture")
        && types.len() >= 3
    {
        return Some(MethodKind::Streaming {
            progress_type: rpc_type_info(&types[0]),
            success_type: rpc_type_info(&types[1]),
            error_type: rpc_type_info(&types[2]),
        });
    }

    if let Type::ImplTrait(impl_trait) = return_ty {
        for bound in &impl_trait.bounds {
            if let TypeParamBound::Trait(tb) = bound
                && let Some(args) = angle_args_for_last_segment(tb.path.segments.last(), "Future")
            {
                for arg in &args.args {
                    if let GenericArgument::AssocType(assoc) = arg
                        && assoc.ident == "Output"
                        && let Some((s, e)) = extract_result_types(&assoc.ty)
                    {
                        return Some(MethodKind::Unary {
                            success_type: s,
                            error_type: e,
                        });
                    }
                }
            }
        }
    }

    if let Some((s, e)) = extract_result_types(return_ty) {
        return Some(MethodKind::Unary {
            success_type: s,
            error_type: e,
        });
    }

    None
}

fn extract_result_types(ty: &Type) -> Option<(RpcTypeInfo, RpcTypeInfo)> {
    let types = path_type_args(ty, "Result")?;
    if types.len() >= 2 {
        Some((rpc_type_info(&types[0]), rpc_type_info(&types[1])))
    } else {
        None
    }
}

fn rpc_type_info(ty: &Type) -> RpcTypeInfo {
    let dart_type = rust_type_to_dart(ty);
    RpcTypeInfo {
        dart_type: dart_type.type_str(),
        decode_expr: dart_type.decode("json"),
        root_types: referenced_custom_type_names(ty),
    }
}

fn path_type_args(ty: &Type, expected_ident: &str) -> Option<Vec<Type>> {
    let Type::Path(tp) = ty else {
        return None;
    };
    let seg = tp.path.segments.last()?;
    if seg.ident != expected_ident {
        return None;
    }
    let PathArguments::AngleBracketed(args) = &seg.arguments else {
        return None;
    };
    Some(
        args.args
            .iter()
            .filter_map(|a| match a {
                GenericArgument::Type(t) => Some(t.clone()),
                _ => None,
            })
            .collect(),
    )
}

fn angle_args_for_last_segment<'a>(
    seg: Option<&'a syn::PathSegment>,
    expected: &str,
) -> Option<&'a AngleBracketedGenericArguments> {
    let seg = seg?;
    if seg.ident != expected {
        return None;
    }
    match &seg.arguments {
        PathArguments::AngleBracketed(args) => Some(args),
        _ => None,
    }
}

fn type_ident(ty: &Type) -> String {
    match ty {
        Type::Path(tp) => tp
            .path
            .segments
            .last()
            .map(|s| s.ident.to_string())
            .unwrap_or_else(|| "Unknown".to_string()),
        _ => "Unknown".to_string(),
    }
}

fn referenced_custom_type_names(ty: &Type) -> Vec<String> {
    let mut out = Vec::new();
    collect_custom_type_names(ty, &mut out);
    out
}

fn collect_custom_type_names(ty: &Type, out: &mut Vec<String>) {
    match ty {
        Type::Path(tp) => {
            let Some(seg) = tp.path.segments.last() else {
                return;
            };
            let ident = seg.ident.to_string();
            match ident.as_str() {
                "i8" | "i16" | "i32" | "i64" | "i128" | "u8" | "u16" | "u32" | "u64" | "u128"
                | "usize" | "isize" | "f32" | "f64" | "bool" | "String" | "str" => {}
                "Option" | "Vec" | "HashMap" | "BTreeMap" | "IndexMap" => {
                    if let PathArguments::AngleBracketed(args) = &seg.arguments {
                        for arg in &args.args {
                            if let GenericArgument::Type(inner) = arg {
                                collect_custom_type_names(inner, out);
                            }
                        }
                    }
                }
                "Infallible" | "Never" => {}
                _ => {
                    if !out.contains(&ident) {
                        out.push(ident);
                    }
                    if let PathArguments::AngleBracketed(args) = &seg.arguments {
                        for arg in &args.args {
                            if let GenericArgument::Type(inner) = arg {
                                collect_custom_type_names(inner, out);
                            }
                        }
                    }
                }
            }
        }
        Type::Reference(reference) => collect_custom_type_names(&reference.elem, out),
        Type::Group(group) => collect_custom_type_names(&group.elem, out),
        Type::Paren(paren) => collect_custom_type_names(&paren.elem, out),
        _ => {}
    }
}

fn extract_roles(attrs: &[Attribute]) -> (bool, Vec<String>) {
    if has_attr(attrs, "public") {
        return (true, Vec::new());
    }
    let mut roles = Vec::new();
    for attr in attrs {
        if attr.path().is_ident("allowed_roles")
            && let Ok(parsed) = attr.parse_args_with(
                syn::punctuated::Punctuated::<syn::LitStr, syn::Token![,]>::parse_terminated,
            )
        {
            roles.extend(parsed.into_iter().map(|s| s.value()));
        }
    }
    (false, roles)
}

fn has_attr(attrs: &[Attribute], name: &str) -> bool {
    attrs.iter().any(|a| a.path().is_ident(name))
}

